import assert from 'node:assert/strict';
import {Engine} from '../dist/engine.js';
import {createState,validateSession} from '../dist/model.js';
const engine = new Engine();
let gain,volume;
engine.ctx = {currentTime:0};
engine.driveGain = {gain:{setTargetAtTime(v){gain=v;}}};
engine.master = {gain:{setTargetAtTime(v){volume=v;}}};
engine.saturation = {};
engine.setDrive(0);
assert.equal(gain,1);
assert.equal(engine.saturation.curve,null);
engine.setDrive(24);
assert.ok(gain>15 && gain<16);
assert.ok(engine.saturation.curve.every(v=>Number.isFinite(v) && Math.abs(v)<=1));
const quiet=.02;
const index=Math.round((quiet*gain+1)/2*4096);
assert.ok(engine.saturation.curve[index]>quiet*10);
engine.setVolume(16);
assert.equal(volume,.9);
engine.setVolume(1);
assert.ok(volume<.05);
const state=createState();
delete state.drive;
validateSession(state);
assert.equal(state.drive,0);
state.drive=25;
assert.throws(()=>validateSession(state));
console.log('PASS: gain boost, bounded saturation, volume range, old-session migration and drive validation.');
